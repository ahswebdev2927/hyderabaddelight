export function getFallbackCategory(slug: string): { name: string; filterTypes: string; imageUrl: string } | null {
  const normalized = decodeURIComponent(slug).toLowerCase().trim().replace(/^\/category\//, "");
  return CATEGORY_SLUG_MAP[normalized] || null;
}

export function getFallbackProductsByCategory(categoryName: string) {
  const norm = categoryName.toLowerCase().trim();
  return DEFAULT_DAIRY_PRODUCTS.filter(
    (p) => p.category.toLowerCase().trim() === norm || norm.includes(p.category.toLowerCase().trim())
  );
}
